// Regenerates `src/registry.ts` and the `@std/*` entries of `deno.json`
// from the JSR metadata for the Deno standard library.
//
// The registry is the interpreter's allow list: a CAD script may import
// exactly the specifiers it names, and nothing else.  Every entry is also a
// statically analysable dynamic import, which is what makes `deno compile`
// embed the module in the binary.  Embedding matters because the sandboxed
// worker runs without import permission and so cannot fetch anything at
// run time.
//
// Usage: deno run -A scripts/gen-registry.ts

const JSR = "https://jsr.io"

